fun getHeroPhrasesForLevel(heroId: String, level: Int, context: QuoteContext): List<String> {
    val tier = quoteTierForLevel(level.coerceIn(1, MAX_HERO_LEVEL))
    if (GameLocaleState.isEnglish) {
        return getHeroPhrasesEnForTier(heroId, tier, context)
    }
    val tiers = HERO_QUOTES_BY_ID[heroId]
    if (tiers != null && tiers.isNotEmpty()) {
        val tierQuotes = tiers[tier.coerceIn(0, tiers.lastIndex)]
        return when (context) {
            QuoteContext.BATTLE_START -> tierQuotes.start
            QuoteContext.VICTORY -> tierQuotes.victory
        }
    }
    return when (context) {
        QuoteContext.BATTLE_START -> when (tier) {
            0 -> listOf("Вступаем в бой! Сил хватит на каждого!")
            1 -> listOf("Магия уже пробудилась — берегитесь!")
            2 -> listOf("Мы стали крепче, пышнее и увереннее в победе!")
            3 -> listOf("Мощь и соблазнительная стать решат исход этой схватки!")
            4 -> listOf("Роскошные формы и горячий нрав готовы к триумфу!")
            else -> listOf("Максимальный жар и пышное совершенство! Победа за нами!")
        }
        QuoteContext.VICTORY -> when (tier) {
            0 -> listOf("Отличная первая победа!")
            1 -> listOf("Наши способности не оставили врагу шансов!")
            2 -> listOf("Красивая и уверенная победа!")
            3 -> listOf("Никто не устоит перед таким сочным мастерством!")
            4 -> listOf("Заслуженный триумф самых ярких воительниц!")
            else -> listOf("Абсолютная победа в полном блеске наших форм!")
        }
    }
}

fun pickHeroBattleQuote(
    card: BattleCard,
    context: QuoteContext,
    random: Random = Random.Default
): HeroBattleQuote? {
    val phrases = getHeroPhrasesForLevel(card.heroId, card.level, context)
    if (phrases.isEmpty()) return null
    val chosen = phrases[random.nextInt(phrases.size)]
    return HeroBattleQuote(
        heroId = card.heroId,
        heroName = card.localizedName(),
        heroLevel = card.level,
        imageRes = resolveHeroFaceDrawableRes(card.heroId, card.imageRes, card.level),
        text = chosen,
        context = context
    )
}
