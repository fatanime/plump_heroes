fun getHeroPhrasesEnForTier(heroId: String, tier: Int, context: QuoteContext): List<String> {
    val tiers = HERO_QUOTES_EN_PART1[heroId] ?: HERO_QUOTES_EN_PART2[heroId]
    if (tiers != null && tiers.isNotEmpty()) {
        val pair = tiers[tier.coerceIn(0, tiers.lastIndex)]
        return when (context) {
            QuoteContext.BATTLE_START -> pair.first
            QuoteContext.VICTORY -> pair.second
        }
    }
    return when (context) {
        QuoteContext.BATTLE_START -> when (tier) {
            0 -> listOf("Into battle! Plenty of strength for everyone!")
            1 -> listOf("Magic has awakened—watch out!")
            2 -> listOf("We've grown tougher, curvier, and ready to win!")
            3 -> listOf("Power and alluring poise will decide this clash!")
            4 -> listOf("Sumptuous curves and fiery spirit are ready for triumph!")
            else -> listOf("Maximum heat and curvy perfection! Victory is ours!")
        }
        QuoteContext.VICTORY -> when (tier) {
            0 -> listOf("A great first victory!")
            1 -> listOf("Our skills left the enemy no chance!")
            2 -> listOf("A handsome and confident victory!")
            3 -> listOf("Nobody withstands skill this juicy!")
            4 -> listOf("A well-earned triumph for the boldest heroines!")
            else -> listOf("Absolute victory in the full splendor of our curves!")
        }
    }
}
